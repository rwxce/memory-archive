// Bundles the browser viewer scripts (lib/exporters/legacy/js/*.js) into ONE
// self-contained classic script and writes it as a TS string constant, so the
// HTML exporter can inline it without reading files at runtime. Before this,
// the CLI read `transcript.js` from disk next to the sources, which is not
// shipped in `dist/`, and the inlined module's relative imports could never
// resolve inside a standalone HTML file.
//
//   node scripts/build-viewer-script.mjs          # regenerate
//   node scripts/build-viewer-script.mjs --check  # exit 1 when out of date
//
// `pnpm build` regenerates it; a test fails when the committed file is stale.

import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JS_DIR = path.join(ROOT, 'lib', 'exporters', 'legacy', 'js');
export const OUTPUT = path.join(JS_DIR, 'viewer-script.generated.ts');

// Dependency order: helpers first, the entry point last.
const SOURCES = ['xss-sanitize.js', 'linkify.js', 'transcript.js'];

/** Drop ESM syntax so the files concatenate into one classic script. */
function stripModuleSyntax(code, file) {
  const out = code
    .replace(/^import\s[^;]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s+(?=(async\s+)?function\b|const\b|let\b|class\b)/gm, '');
  if (/^\s*(import|export)\b/m.test(out)) {
    throw new Error(`${file}: unsupported import/export form for the viewer bundle`);
  }
  return out;
}

export function buildViewerScript() {
  const body = SOURCES.map((f) => {
    const code = fs.readFileSync(path.join(JS_DIR, f), 'utf8');
    return `// ---- ${f} ----\n${stripModuleSyntax(code, f).trim()}\n`;
  }).join('\n');
  return `(function () {\n'use strict';\n${body}})();\n`;
}

export function renderGeneratedModule() {
  const script = buildViewerScript();
  return (
    '// GENERATED by scripts/build-viewer-script.mjs from lib/exporters/legacy/js/*.js.\n' +
    '// Do not edit: change the .js sources and run `node scripts/build-viewer-script.mjs`.\n\n' +
    '/** Self-contained classic script for the generated messages.html viewer. */\n' +
    `export const VIEWER_SCRIPT = ${JSON.stringify(script)};\n`
  );
}

function main() {
  const next = renderGeneratedModule();
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('[build-viewer-script] out of date: run node scripts/build-viewer-script.mjs');
      process.exit(1);
    }
    return;
  }
  if (current !== next) fs.writeFileSync(OUTPUT, next);
  console.log('[build-viewer-script] wrote', path.relative(ROOT, OUTPUT));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
