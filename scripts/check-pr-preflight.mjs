#!/usr/bin/env node
/**
 * PR preflight — catches changes that make the branch unsafe to publish, not
 * changes that expand what the diff does.
 *
 * These are "completions", not "extensions" (see the pr-scope skill): the
 * branch is already wrong without the fix, regardless of which files the fix
 * lives in. Rules:
 *
 *   1. .gitignore must keep ignoring .env files and the private-data folders
 *      (fixtures/, data/, output/, backup/).
 *   2. No real env file (.env, .env.local, .env.production.local, ...) may be
 *      added. `.env.example` / `.env.local.example` are the only exceptions.
 *   3. No real WhatsApp export or personal media may be added: any *.zip,
 *      any `_chat.txt` / `WhatsApp Chat*.txt`, WhatsApp-named or common
 *      audio/video/photo files, or any file under fixtures/, data/, output/,
 *      backup/.
 *      Test fixtures are synthetic and generated by
 *      scripts/generate-fixtures.mjs at test time — never committed.
 *
 * Plus one non-blocking warning: a diff above ~15 files or ~800 changed lines
 * should probably be split (see /pr-plan).
 *
 * Blocking by default (exit 1). Pass --advisory to always exit 0 — that is how
 * the Stop hook runs it, so a half-finished turn is warned, not blocked.
 *
 * Base resolution: GITHUB_BASE_REF / PR_BASE_REF (CI pull_request),
 * PUSH_BEFORE_SHA (CI push), else the merge-base with origin/dev, then
 * origin/main, then main (local runs).
 */

import { execFileSync } from 'node:child_process';

const ADVISORY = process.argv.includes('--advisory');
const MAX_FILES = 15;
const MAX_LINES = 800;
const PRIVATE_DIRS = ['fixtures', 'data', 'output', 'backup'];

function git(args) {
  try {
    return execFileSync('git', args, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
      maxBuffer: 32 * 1024 * 1024,
    });
  } catch {
    return '';
  }
}

function resolveBase() {
  const baseRef = process.env.GITHUB_BASE_REF || process.env.PR_BASE_REF;
  if (baseRef) {
    const b =
      git(['merge-base', 'HEAD', `origin/${baseRef}`]).trim() ||
      git(['merge-base', 'HEAD', baseRef]).trim();
    if (b) return b;
  }
  const pushBefore = process.env.PUSH_BEFORE_SHA;
  if (pushBefore && !/^0+$/.test(pushBefore)) {
    const b = git(['rev-parse', '--verify', '--quiet', `${pushBefore}^{commit}`]).trim();
    if (b) return b;
  }
  for (const ref of ['origin/dev', 'origin/main', 'main']) {
    const base = git(['merge-base', 'HEAD', ref]).trim();
    if (base) return base;
  }
  return '';
}

const base = resolveBase();
if (!base) {
  // In CI a missing base (shallow checkout) must not silently pass the gate.
  if (process.env.CI && !ADVISORY) {
    console.log('PR preflight: could not resolve the base commit (shallow checkout? use fetch-depth: 0).');
    process.exit(1);
  }
  process.exit(0);
}

// Includes uncommitted working-tree changes on purpose: the Stop hook runs
// mid-work, before anything is committed.
const diff = git(['diff', '--unified=0', base]);
const untracked = git(['ls-files', '--others', '--exclude-standard'])
  .split('\n')
  .filter(Boolean);
if (!diff && untracked.length === 0) process.exit(0);

const problems = [];
const warnings = [];

// --- Rule 1: .gitignore protection weakened --------------------------------
{
  const removed = git(['diff', '--unified=0', base, '--', '.gitignore'])
    .split('\n')
    .filter((l) => l.startsWith('-') && !l.startsWith('---'))
    .map((l) => l.slice(1).trim())
    // A removed comment or negation does not weaken protection.
    .filter((body) => body && !body.startsWith('#') && !body.startsWith('!'));

  if (removed.some((body) => /\.env/.test(body))) {
    problems.push({
      label: '.gitignore no longer ignores .env',
      detail: 'A line matching .env was removed from .gitignore. Restore it — secrets must never be committed.',
    });
  }
  for (const dir of PRIVATE_DIRS) {
    if (removed.some((body) => body.replace(/^\/|\/$/g, '') === dir)) {
      problems.push({
        label: `.gitignore no longer ignores ${dir}/`,
        detail: `${dir}/ may hold real chat exports or generated backups. Restore the ignore line.`,
      });
    }
  }
}

// --- Rules 2 and 3: forbidden files added ---------------------------------
{
  const added = new Set([
    ...git(['diff', '--name-only', '--diff-filter=A', base]).split('\n').filter(Boolean),
    ...untracked,
  ]);

  for (const f of added) {
    if (/(^|\/)\.env(\..+)?$/.test(f) && !/(^|\/)\.env(\.local)?\.example$/.test(f)) {
      problems.push({
        label: `Real env file added: ${f}`,
        detail: 'Only .env.example / .env.local.example may be committed. Remove it and rotate any secret it held.',
      });
    } else if (
      /\.zip$/i.test(f) ||
      /(^|\/)_chat\.txt$/.test(f) ||
      /(^|\/)WhatsApp Chat[^/]*\.txt$/i.test(f)
    ) {
      problems.push({
        label: `Possible real WhatsApp export added: ${f}`,
        detail: 'Never commit chat exports. Tests use synthetic fixtures from scripts/generate-fixtures.mjs.',
      });
    } else if (
      /(^|\/)(?:IMG|VID|PTT|AUD|STK|DOC)-\d{8}-WA\d{4}\./i.test(f) ||
      /\.(?:opus|m4a|mp4|mov|heic|jpe?g)$/i.test(f)
    ) {
      problems.push({
        label: `Possible personal media added: ${f}`,
        detail: 'WhatsApp media (photos, voice notes, videos) is personal data. Tests generate synthetic media instead.',
      });
    } else if (PRIVATE_DIRS.some((dir) => f.startsWith(`${dir}/`))) {
      problems.push({
        label: `Private-data folder file added: ${f}`,
        detail: 'fixtures/, data/, output/ and backup/ are local-only. Remove the file from the diff.',
      });
    }
  }
}

// --- Warning: PR size -------------------------------------------------------
{
  const stat = git(['diff', '--numstat', base]).split('\n').filter(Boolean);
  const files = stat.length;
  const lines = stat.reduce((sum, row) => {
    const [a, d] = row.split('\t');
    return sum + (Number(a) || 0) + (Number(d) || 0);
  }, 0);
  if (files > MAX_FILES || lines > MAX_LINES) {
    warnings.push(
      `Diff is ${files} files / ${lines} lines (guide: ~${MAX_FILES} files / ~${MAX_LINES} lines). Consider splitting it (/pr-plan).`,
    );
  }
}

for (const w of warnings) console.log(`PR preflight (warning): ${w}`);

if (problems.length === 0) process.exit(0);

console.log('\nPR preflight — this branch is not safe to publish:\n');
for (const { label, detail } of problems) {
  console.log(`  - ${label}\n      ${detail}`);
}
console.log();

process.exit(ADVISORY ? 0 : 1);
